#!/usr/bin/env python3
"""Generate deterministic, losslessly compressed native frontend resources."""
import argparse
import gzip
import io
import json
from pathlib import Path


def encode_asset(data):
    buffer = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buffer,
                       compresslevel=9, mtime=0) as stream:
        stream.write(data)
    compressed = buffer.getvalue()
    return (compressed, True) if len(compressed) < len(data) else (data, False)


def generate(root, output, version):
    entries = []
    original_size = stored_size = 0
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write('// Generated by embed_web_assets.py. DO NOT EDIT.\n'
                     '#include "web/static_assets.hpp"\n'
                     'namespace acecode::web {\n')
        for path in sorted(root.rglob("*")) if root.exists() else []:
            if not path.is_file() or path.name in {"README.md", ".gitignore"}:
                continue
            relative = path.relative_to(root).as_posix()
            raw = path.read_bytes()
            if relative == "index.html":
                raw = raw.replace(b"__VERSION__", version.encode("utf-8"))
            data, compressed = encode_asset(raw)
            name = f"asset_{len(entries)}"
            stream.write(f"static const unsigned char {name}[] = {{\n")
            for offset in range(0, len(data), 24):
                stream.write("".join(f"0x{byte:02x}," for byte in data[offset:offset + 24]) + "\n")
            if not data:
                stream.write("0\n")
            stream.write("};\n")
            entries.append(f"    {{{json.dumps(relative)}, {{{name}, {len(data)}, "
                           f"{len(raw)}, {'true' if compressed else 'false'}}}}},\n")
            original_size += len(raw)
            stored_size += len(data)
        stream.write("const std::map<std::string, EmbeddedAsset>& embedded_asset_map() {\n"
                     "    static const std::map<std::string, EmbeddedAsset> assets = {\n")
        stream.writelines(entries)
        stream.write("    };\n    return assets;\n}\n}\n")
    print(f"[acecode_embed_assets] {len(entries)} assets: {original_size} -> {stored_size} bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--version", required=True)
    args = parser.parse_args()
    generate(args.root, args.output, args.version)

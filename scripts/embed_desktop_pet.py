"""Embed the classic pet page, local scripts and the HD pet sheets without network IO."""

import argparse
import json
import pathlib
import re

FOLDERS = {"clippy": "classic/clippy", "rover": "classic/rover", "whale": "whale"}


def hd_sheets(root, kind):
    """The HD sheet files of hd/frames.js in order; their count must match the frame table."""
    folder = root / FOLDERS[kind] / "hd"
    table = (folder / "frames.js").read_text(encoding="utf-8")
    count = len(json.loads(table[table.index("= {") + 2:table.rindex(";")])["sheets"])
    files = [folder / f"sheet-{index:02d}.webp" for index in range(count)]
    extra = sorted(set(folder.glob("sheet-*.webp")) - set(files))
    if not all(path.exists() for path in files) or extra:
        raise ValueError(f"{folder}: sheet files do not match frames.js ({count} sheets)")
    return files


def write_blob(out, name, data):
    """Bytes as 64-bit little-endian words: an eighth of the tokens of a byte list, so large sheets compile fast."""
    padded = data + b"\0" * (-len(data) % 8)
    words = [int.from_bytes(padded[i:i + 8], "little") for i in range(0, len(padded), 8)]
    out.write(f"alignas(8) static const unsigned long long {name}_words[] = {{\n")
    for start in range(0, len(words), 12):
        out.write(",".join(f"0x{word:x}ull" for word in words[start:start + 12]) + ",\n")
    out.write("};\n")


def bytes_of(name):
    return f"reinterpret_cast<const unsigned char*>({name}_words)"


def embed(root, output):
    root = root.resolve()
    page = (root / "classic_pet.html").read_text(encoding="utf-8")

    def inline(match):
        source = (root / match[1]).resolve()
        source.relative_to(root)  # Reject scripts outside the asset directory (Python 3.8 compatible).
        script = source.read_text(encoding="utf-8").replace("</script", "<\\/script")
        return "<script>" + script + "</script>"

    page = re.sub(r'<script src="([^\"]+)"></script>', inline, page)
    encoded = page.encode("utf-8")
    if len(encoded) >= 2 * 1024 * 1024 or '<script src=' in page:
        raise ValueError("Pet page must be self-contained and below the WebView2 2 MiB limit")
    output.parent.mkdir(parents=True, exist_ok=True)
    total = 0
    with output.open("w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by scripts/embed_desktop_pet.py\n#include <cstddef>\nnamespace acecode {\n")
        write_blob(out, "classic_pet_page", encoded)
        out.write(f"const unsigned char* classic_pet_page_data() {{ return {bytes_of('classic_pet_page')}; }}\n")
        out.write(f"std::size_t classic_pet_page_size() {{ return {len(encoded)}; }}\n")
        for kind, folder in FOLDERS.items():
            # The pet peeking from a screen edge while docked (two frames: eyes open / blink).
            peek = (root / folder / "peek.png").read_bytes()
            write_blob(out, f"{kind}_peek", peek)
            out.write(f"const unsigned char* {kind}_pet_peek_data() {{ return {bytes_of(kind + '_peek')}; }}\n")
            out.write(f"std::size_t {kind}_pet_peek_size() {{ return {len(peek)}; }}\n")
            # HD animation sheets, in the order of hd/frames.js.
            sheets = [path.read_bytes() for path in hd_sheets(root, kind)]
            for index, data in enumerate(sheets):
                total += len(data)
                write_blob(out, f"{kind}_sheet{index}", data)
            pointers = ", ".join(bytes_of(f"{kind}_sheet{index}") for index in range(len(sheets)))
            sizes = ", ".join(str(len(data)) for data in sheets)
            out.write(f"static const unsigned char* const {kind}_sheets[] = {{{pointers}}};\n")
            out.write(f"static const std::size_t {kind}_sheet_sizes[] = {{{sizes}}};\n")
            out.write(f"std::size_t {kind}_pet_sheet_count() {{ return {len(sheets)}; }}\n")
            out.write(f"const unsigned char* {kind}_pet_sheet_data(std::size_t index) {{ return {kind}_sheets[index]; }}\n")
            out.write(f"std::size_t {kind}_pet_sheet_size(std::size_t index) {{ return {kind}_sheet_sizes[index]; }}\n")
        out.write("}\n")
    print(f"Embedded companion pet page ({len(encoded)} bytes), 3 edge-peek sheets and "
          f"{total / 1e6:.1f} MB of HD animation sheets")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()
    embed(args.root, args.output)

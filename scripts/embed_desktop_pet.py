"""Embed the classic pet page, local scripts and original PNGs without network IO."""

import argparse
import pathlib
import re


def embed(root, output):
    root = root.resolve()
    page = (root / "classic_pet.html").read_text(encoding="utf-8")

    def inline(match):
        source = (root / match[1]).resolve()
        source.relative_to(root)  # Reject scripts outside the asset directory (Python 3.8 compatible).
        script = source.read_text(encoding="utf-8").replace("</script", "<\\/script")
        return "<script>" + script + "</script>"

    page = re.sub(r'<script src="([^\"]+)"></script>', inline, page)
    encoded = page.encode("utf-8")
    if len(encoded) >= 2 * 1024 * 1024 or '<script src=' in page:
        raise ValueError("Pet page must be self-contained and below the WebView2 2 MiB limit")
    resources = {"classic_pet_page": encoded}
    for kind in ("clippy", "rover", "whale"):
        folder = root / "whale" if kind == "whale" else root / "classic" / kind
        resources[kind + "_pet_sprite"] = (folder / "map.png").read_bytes()
    # Whale Girl peeking from a screen edge while docked (two frames: eyes open / blink).
    resources["whale_pet_peek"] = (root / "whale" / "peek.png").read_bytes()
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by scripts/embed_desktop_pet.py\n#include <cstddef>\nnamespace acecode {\n")
        for name, data in resources.items():
            out.write(f"static const unsigned char {name}_bytes[] = {{\n")
            for start in range(0, len(data), 128):
                out.write(",".join(str(byte) for byte in data[start:start + 128]) + ",\n")
            out.write(f"}};\nconst unsigned char* {name}_data() {{ return {name}_bytes; }}\n")
            out.write(f"std::size_t {name}_size() {{ return {len(data)}; }}\n")
        out.write("}\n")
    print(f"Embedded companion pet page ({len(encoded)} bytes), 3 sprite sheets and the whale peek sheet")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()
    embed(args.root, args.output)

"""Turn Rover's Grok videos into the HD frame sheets and animation table the pet player loads.

Run with a Python that has PyAV (`av`), numpy and Pillow. Frames are keyed off the green screen, taken at
12 fps, scaled so the original 80x80 sprite box becomes OUTPUT pixels, trimmed and packed in playback order
(hd_assemble.pack). Unlike Clippy and Whale Girl, Rover's animation timing comes from the videos, so
hd/frames.js carries its own `agent` table (same animation names as agent.js, which the player prefers).
"""

import argparse
import json
import pathlib
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from grok_rover_videos import BOX, CANVAS, CLIPS  # noqa: E402
from grok_video_frames import frames, key  # noqa: E402
from hd_assemble import pack  # noqa: E402

OUTPUT = 360            # the sprite box in HD pixels (4.5x the original 80px frame)
FPS = 12
SCALE = OUTPUT / BOX
ORIGIN = ((CANVAS - BOX) // 2, CANVAS - BOX)   # sprite box position inside the video canvas


def scaled(image):
    size = round(CANVAS * SCALE)
    a = np.asarray(image, np.float32)
    pm = a.copy()
    pm[..., :3] *= a[..., 3:4] / 255.0
    channels = [np.asarray(Image.fromarray(pm[..., c]).resize((size, size), Image.LANCZOS), np.float32)
                for c in range(4)]
    w = np.dstack(channels)
    alpha = np.clip(w[..., 3], 0, 255)
    colour = np.where(alpha[..., None] > 0.5, w[..., :3] * 255.0 / np.maximum(alpha[..., None], 1e-3), 0)
    alpha[alpha < 3] = 0
    return Image.fromarray(np.dstack([np.clip(colour, 0, 255), alpha]).astype(np.uint8))


def clip_frames(path, looping):
    decoded = frames(path)
    step = max(1, round(len(decoded) / (decoded[-1][0] + 1 / 24) / FPS)) if len(decoded) > 1 else 1
    picked = decoded[::step]
    if looping and len(picked) > 1:
        picked = picked[:-1]   # the last frame is the first one again
    duration = round(1000 * step / 24)
    return [key(rgb) for _, rgb in picked], duration


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=pathlib.Path, required=True, help="assets/desktop_pet")
    parser.add_argument("--work", type=pathlib.Path, required=True, help="grok_rover_videos.py work directory")
    parser.add_argument("--quality", type=int, default=75)
    args = parser.parse_args()
    ox, oy = round(ORIGIN[0] * SCALE), round(ORIGIN[1] * SCALE)
    base = key(np.asarray(Image.open(args.work / "base_padded.png").convert("RGB")))
    clips = {"RestPose": ([base], 100)}
    for name in CLIPS:
        clips[name] = clip_frames(args.work / f"{name}.mp4", looping=name != "Show")
    items, animations = [], {}
    for index, (name, (pictures, duration)) in enumerate(clips.items()):
        frames_out = []
        for number, picture in enumerate(pictures):
            picture = scaled(picture)
            box = picture.getchannel("A").getbbox()
            if not box:
                continue
            box = (max(0, box[0] - 1), max(0, box[1] - 1), min(picture.width, box[2] + 1), min(picture.height, box[3] + 1))
            items.append(((index, number), picture.crop(box), box[0] - ox, box[1] - oy))
            frames_out.append({"duration": duration, "images": [[index, number]]})
        animations[name] = {"frames": frames_out}
    out = args.root / "classic" / "rover" / "hd"
    out.mkdir(exist_ok=True)
    for old in out.glob("sheet-*.webp"):
        old.unlink()
    offsets = {key_: (dx, dy) for key_, _, dx, dy in items}
    table, sheets, groups = {}, [], {}
    for name, (pictures, _) in clips.items():
        index = list(clips).index(name)
        mine = [(key_, picture) for key_, picture, _, _ in items if key_[0] == index]
        for image, spots in pack(mine):
            sheet_index = len(sheets)
            image.save(out / f"sheet-{sheet_index:02d}.webp", "WEBP", quality=args.quality, method=6)
            sheets.append(list(image.size))
            for key_, (sx, sy) in spots.items():
                picture = dict(mine)[key_]
                table[f"{key_[0]},{key_[1]}"] = [sheet_index, sx, sy, *picture.size, *offsets[key_]]
            groups.setdefault(name, []).append(sheet_index)
    agent = {"framesize": [80, 80], "animations": animations}
    data = {"framesize": [OUTPUT, OUTPUT], "sheets": sheets, "animations": groups, "frames": table, "agent": agent}
    (out / "frames.js").write_text(
        "// Generated by scripts/desktop_pet/grok_rover_assemble.py: Rover animated from green-screen videos made\n"
        "// with Grok Imagine (reference_to_video); `agent` replaces agent.js timing for this pet.\n"
        f"(window.ClassicPetHD = window.ClassicPetHD || {{}}).rover = {json.dumps(data, separators=(',', ':'))};\n",
        encoding="utf-8")
    total = sum((out / f"sheet-{i:02d}.webp").stat().st_size for i in range(len(sheets)))
    print(f"rover: {len(clips)} animations, {len(table)} frames, {len(sheets)} sheets, {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main()

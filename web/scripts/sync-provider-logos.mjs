import { createHash } from 'node:crypto';
import {
  mkdir,
  readFile,
  rename,
  rm,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDir, '..');
const repoRoot = path.resolve(webRoot, '..');
const publicDir = path.join(webRoot, 'public');
const destination = path.join(publicDir, 'provider-logos');
const generatedModule = path.join(webRoot, 'src', 'lib', 'providerLogos.generated.js');
const catalogPath = path.join(repoRoot, 'assets', 'models_dev', 'api.json');
const sourceBaseUrl = 'https://models.dev/logos';
const maxConcurrentRequests = 16;
const maxLogoBytes = 100 * 1024;
const maxBundledSvgBytes = 512 * 1024;

function assertChildPath(parent, target) {
  const relative = path.relative(path.resolve(parent), path.resolve(target));
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(`refusing to replace path outside ${parent}: ${target}`);
  }
}

function sanitizeSvg(raw, providerId) {
  let svg = raw.toString('utf8')
    .replace(/^\uFEFF/u, '')
    .replace(/<\?xml[\s\S]*?\?>/giu, '')
    .replace(/<!DOCTYPE[\s\S]*?>/giu, '')
    .trim();
  if (!/<svg\b/iu.test(svg)) {
    throw new Error(`${providerId}: response is not SVG`);
  }
  if (/<script\b|on[a-z]+\s*=|(?:href|xlink:href|src)\s*=\s*["']\s*(?:https?:|javascript:)|url\(\s*["']?\s*https?:/iu.test(svg)) {
    throw new Error(`${providerId}: SVG contains active or remote content`);
  }
  svg += '\n';
  const bytes = Buffer.from(svg, 'utf8');
  if (bytes.length === 0 || bytes.length > maxLogoBytes) {
    throw new Error(`${providerId}: SVG size ${bytes.length} exceeds the per-logo budget`);
  }
  return bytes;
}

async function fetchLogo(providerId) {
  const response = await fetch(`${sourceBaseUrl}/${encodeURIComponent(providerId)}.svg`, {
    headers: { 'User-Agent': 'ACECode provider logo sync' },
    signal: AbortSignal.timeout(20_000),
  });
  if (!response.ok) {
    throw new Error(`${providerId}: HTTP ${response.status}`);
  }
  return sanitizeSvg(Buffer.from(await response.arrayBuffer()), providerId);
}

async function mapConcurrent(values, concurrency, worker) {
  const results = new Array(values.length);
  let cursor = 0;
  async function consume() {
    while (cursor < values.length) {
      const index = cursor;
      cursor += 1;
      results[index] = await worker(values[index], index);
    }
  }
  await Promise.all(Array.from(
    { length: Math.min(concurrency, values.length) },
    () => consume(),
  ));
  return results;
}

function generatedModuleSource(assetByProvider, rasterAssets) {
  const entries = Object.entries(assetByProvider)
    .map(([providerId, assetId]) => `  ${JSON.stringify(providerId)}: ${JSON.stringify(assetId)},`)
    .join('\n');
  const rasters = [...rasterAssets]
    .sort()
    .map((assetId) => `  ${JSON.stringify(assetId)},`)
    .join('\n');
  return `// Generated by web/scripts/sync-provider-logos.mjs. Do not edit.\n`
    + `export const PROVIDER_LOGO_ASSET_BY_ID = Object.freeze({\n${entries}\n});\n\n`
    + `export const RASTER_PROVIDER_LOGO_ASSET_IDS = new Set([\n${rasters}\n]);\n`;
}

async function replaceDirectory(tempDirectory) {
  assertChildPath(publicDir, destination);
  const backup = `${destination}.backup-${process.pid}`;
  await rm(backup, { recursive: true, force: true });
  let hadDestination = false;
  try {
    await rename(destination, backup);
    hadDestination = true;
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  try {
    await rename(tempDirectory, destination);
  } catch (error) {
    if (hadDestination) await rename(backup, destination);
    throw error;
  }
  if (hadDestination) await rm(backup, { recursive: true, force: true });
}

const catalogBytes = await readFile(catalogPath);
const catalog = JSON.parse(catalogBytes.toString('utf8'));
const providerIds = Object.keys(catalog).sort();
if (providerIds.length < 50 || providerIds.some((id) => !/^[a-z0-9][a-z0-9._-]*$/u.test(id))) {
  throw new Error('models.dev catalog contains an invalid Provider ID set');
}

const fetched = await mapConcurrent(providerIds, maxConcurrentRequests, async (providerId) => ({
  providerId,
  bytes: await fetchLogo(providerId),
}));

const uniqueByHash = new Map();
const assetByProvider = {};
for (const item of fetched) {
  const hash = createHash('sha256').update(item.bytes).digest('hex');
  const existing = uniqueByHash.get(hash);
  const assetId = existing?.providerId || item.providerId;
  if (!existing) uniqueByHash.set(hash, item);
  assetByProvider[item.providerId] = assetId;
}

const uniqueAssets = [...uniqueByHash.values()];
const bundledSvgBytes = uniqueAssets.reduce((total, item) => total + item.bytes.length, 0);
if (bundledSvgBytes > maxBundledSvgBytes) {
  throw new Error(`provider logos total ${bundledSvgBytes} exceeds ${maxBundledSvgBytes} bytes`);
}

const tempDirectory = `${destination}.tmp-${process.pid}-${Date.now()}`;
assertChildPath(publicDir, tempDirectory);
await mkdir(tempDirectory, { recursive: false });
try {
  await Promise.all(uniqueAssets.map((item) => (
    writeFile(path.join(tempDirectory, `${item.providerId}.svg`), item.bytes)
  )));
  const rasterAssets = new Set(uniqueAssets
    .filter((item) => item.bytes.includes(Buffer.from('data:image/')))
    .map((item) => item.providerId));
  const manifest = {
    source: `${sourceBaseUrl}/{provider}.svg`,
    catalog_content_sha256: createHash('sha256').update(catalogBytes).digest('hex'),
    provider_count: providerIds.length,
    unique_asset_count: uniqueAssets.length,
    bundled_svg_bytes: bundledSvgBytes,
    max_bundled_svg_bytes: maxBundledSvgBytes,
  };
  await writeFile(
    path.join(tempDirectory, 'MANIFEST.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    path.join(tempDirectory, 'README.md'),
    '# Provider logos\n\n'
      + 'Generated from the official `https://models.dev/logos/{provider}.svg` endpoint.\n'
      + 'Duplicate SVG payloads are stored once; the generated JS map preserves every Provider ID.\n'
      + 'The upstream models.dev MIT attribution is bundled at `assets/models_dev/LICENSE`.\n',
    'utf8',
  );
  const generatedTemp = `${generatedModule}.tmp-${process.pid}`;
  await writeFile(generatedTemp, generatedModuleSource(assetByProvider, rasterAssets), 'utf8');
  await replaceDirectory(tempDirectory);
  await rename(generatedTemp, generatedModule);
  process.stdout.write(
    `Provider logos synced: providers=${providerIds.length} unique=${uniqueAssets.length} bytes=${bundledSvgBytes}\n`,
  );
} catch (error) {
  await rm(tempDirectory, { recursive: true, force: true });
  throw error;
}

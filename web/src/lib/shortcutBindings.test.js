import assert from 'node:assert/strict';
import { APP_SHORTCUTS, SHORTCUT_STORAGE_KEY, bindingLabel, captureShortcut, createShortcutStore,
  composerShortcutAction, effectiveShortcut, matchesShortcutBinding, shortcutBindingsConflict, shortcutEventVariants, validateShortcut } from './shortcutBindings.js';

const chord = (code, extra = {}) => captureShortcut({ code, ctrlKey: true, altKey: true, ...extra });
const memory = () => {
  const data = new Map();
  return { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value), data };
};
const storage = memory();
const events = new EventTarget();
const store = createShortcutStore(storage, events);
let notifications = 0;
const unsubscribe = store.subscribe(() => notifications++);
const custom = chord('KeyJ');
assert.deepEqual(store.save('newSession', custom), { ok: true });
assert.equal(notifications, 1);
assert.equal(bindingLabel(effectiveShortcut('newSession', store.getSnapshot())), 'Ctrl+Alt+J');
assert.equal(matchesShortcutBinding({ code: 'KeyN', ctrlKey: true, altKey: true }, effectiveShortcut('newSession', store.getSnapshot())), false);
assert.equal(matchesShortcutBinding({ code: 'KeyJ', ctrlKey: true, altKey: true }, effectiveShortcut('newSession', store.getSnapshot())), true);
const reloaded = createShortcutStore(storage, events);
assert.deepEqual(reloaded.getSnapshot(), store.getSnapshot());
assert.deepEqual(store.save('focusInput', custom), { ok: false, reason: 'conflict', conflict: 'newSession' });
assert.deepEqual(store.save('newSession', chord('Period', { shiftKey: true })), { ok: false, reason: 'conflict', conflict: 'reasoningUp' });
assert.equal(store.save('newSession', chord('KeyC', { altKey: false })).reason, 'reserved');
assert.equal(store.save('newSession', chord('KeyJ', { ctrlKey: false, altKey: false })).reason, 'modifier');
assert.equal(store.save('newSession', chord('F11', { ctrlKey: false, altKey: false })).reason, 'reserved');
assert.equal(store.save('missing', custom).reason, 'invalid');
assert.equal(store.save('newSession', { ...custom, code: 'NotAKey' }).reason, 'invalid');
assert.equal(store.save('newSession', { ...custom, key: '<script>' }).reason, 'invalid');
assert.deepEqual(store.save('focusInput', chord('KeyN')), { ok: true });
assert.equal(store.save('newSession', null).reason, 'conflict', 'restoring cannot silently steal another binding');
assert.deepEqual(store.save('focusInput', null), { ok: true });
assert.deepEqual(store.save('newSession', null), { ok: true });
assert.deepEqual(store.getSnapshot(), {});
assert.deepEqual(store.save('newSession', custom), { ok: true });
const before = store.getSnapshot();
storage.setItem = () => { throw new Error('quota exceeded'); };
assert.deepEqual(store.save('newSession', chord('KeyU')), { ok: false, reason: 'storage' });
assert.equal(store.getSnapshot(), before, 'failed save keeps active bindings');
assert.deepEqual(createShortcutStore(null).save('newSession', custom), { ok: false, reason: 'storage' });
storage.data.set(SHORTCUT_STORAGE_KEY, JSON.stringify({ newSession: chord('KeyU') }));
const storageEvent = new Event('storage');
Object.defineProperty(storageEvent, 'key', { value: SHORTCUT_STORAGE_KEY });
events.dispatchEvent(storageEvent);
assert.equal(store.getSnapshot().newSession.code, 'KeyU');
unsubscribe();
const malformed = memory();
malformed.setItem(SHORTCUT_STORAGE_KEY, '{broken');
assert.deepEqual(createShortcutStore(malformed).getSnapshot(), {});
malformed.setItem(SHORTCUT_STORAGE_KEY, JSON.stringify({ newSession: chord('KeyI') }));
assert.deepEqual(createShortcutStore(malformed).getSnapshot(), {}, 'conflicting storage falls back to valid defaults');
assert.equal(captureShortcut({ code: 'ControlLeft', ctrlKey: true }), null);
assert.equal(captureShortcut({ code: 'KeyJ', ctrlKey: true, isComposing: true }), null);
assert.equal(captureShortcut({ code: 'KeyJ', ctrlKey: true, repeat: true }), null);
assert.equal(captureShortcut({ code: 'KeyJ', ctrlKey: true, getModifierState: () => true }), null);
assert.equal(matchesShortcutBinding({ code: 'KeyJ', ctrlKey: true, altKey: true, target: { closest: () => ({}) } }, custom), false);
assert.equal(matchesShortcutBinding({ code: 'KeyJ', ctrlKey: true, altKey: true, shiftKey: true }, custom), false);
assert.equal(composerShortcutAction({ key: 'Enter', code: 'Enter', ctrlKey: true }, true, { newline: chord('KeyJ') }), 'ignore', 'old desktop newline must not become a send action');
assert.equal(composerShortcutAction({ key: 'Enter', code: 'Enter' }, false, { send: chord('KeyJ') }), null);
assert.equal(composerShortcutAction({ key: 'Enter', code: 'Enter', ctrlKey: true }, true, {}), 'newline');
assert.equal(shortcutBindingsConflict(APP_SHORTCUTS.reasoningUp, chord('Period', { shiftKey: true })), true);
assert.equal(shortcutBindingsConflict(APP_SHORTCUTS.reasoningUp, chord('Comma')), false);
assert.equal(matchesShortcutBinding({ key: '-', code: 'NumpadSubtract', ctrlKey: true }, APP_SHORTCUTS.forward), true);
assert.equal(matchesShortcutBinding({ key: 'k', code: 'KeyT', ctrlKey: true }, APP_SHORTCUTS.search), true);
assert.deepEqual(shortcutEventVariants(custom), [{ key: 'J', code: 'KeyJ', ctrlKey: true, metaKey: false, altKey: true, shiftKey: false }]);
for (const [id, code, extra] of [['send', 'Enter', { altKey: false }], ['newline', 'KeyJ', {}], ['save', 'KeyG', {}], ['dismiss', 'KeyQ', {}], ['find', 'KeyF', {}], ['historyPrevious', 'ArrowUp', {}]]) {
  assert.equal(validateShortcut(id, chord(code, extra)), null, id);
}
console.log('[pass] editable shortcuts: persistence, conflicts, reset, storage failure, window sync, corruption, capture and contexts');
